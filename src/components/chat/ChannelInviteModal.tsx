import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogClose,
  DialogContent,
  DialogDescription,
  DialogTitle,
} from "@/components/ui/dialog";
import { IconButton } from "@/components/ui/IconButton";
import { Input } from "@/components/ui/input";
import { apiPost } from "@/lib/api-client";
import { getAuthAssetUrl, getWebOrigin } from "@/lib/platform";
import type { Channel, Relationship } from "@/lib/types";
import { cn } from "@/lib/utils";
import { useChatStore } from "@/stores/chat-store";
import { useEffect, useId, useMemo, useState } from "react";
import { AvatarImage } from "./AvatarImage";
import { Icon } from "@/components/ui/icon";
import InlineEmojiText from "./InlineEmojiText";

interface ChannelInviteModalProps {
  open: boolean;
  serverId: string;
  serverName: string;
  channel: Channel;
  onClose: () => void;
}

export default function ChannelInviteModal({
  open,
  serverId,
  serverName,
  channel,
  onClose,
}: ChannelInviteModalProps) {
  const relationships = useChatStore((s) => s.relationships);
  const friendSearchInputId = useId();
  const inviteLinkInputId = useId();
  const [state, setState] = useState<{
    search: string;
    inviteCode: string;
    loading: boolean;
    copied: boolean;
    invitedUsers: Set<string>;
  }>({
    search: "",
    inviteCode: "",
    loading: true,
    copied: false,
    invitedUsers: new Set(),
  });
  const [_invitedUsers, _setInvitedUsers] = useState<Set<string>>(new Set());

  useEffect(() => {
    if (!open) return;
    // Do not reuse an invite generated by the previous open cycle.
    setState({
      search: "",
      inviteCode: "",
      loading: true,
      copied: false,
      invitedUsers: new Set(),
    });
  }, [open, serverId, channel.id]);

  // Filter to accepted friends only (type 0)
  const friends = useMemo(
    () => relationships.filter((r: Relationship) => r.type === 0),
    [relationships],
  );

  const filteredFriends = useMemo(() => {
    if (!state.search.trim()) return friends;
    const q = state.search.toLowerCase();
    return friends.filter(
      (r: Relationship) =>
        r.user.username.toLowerCase().includes(q) ||
        (r.user.display_name?.toLowerCase().includes(q) ?? false),
    );
  }, [friends, state.search]);

  // Auto-create a channel-scoped invite on open
  useEffect(() => {
    let cancelled = false;
    async function createInvite() {
      try {
        const data = await apiPost<{ code: string }>(
          `/api/servers/${serverId}/invites`,
          {
            channel_id: channel.id,
            max_age: 604800, // 7 days
          },
        );
        if (!cancelled)
          setState((prev) => ({ ...prev, inviteCode: data.code }));
      } catch (err) {
        console.error("Failed to create invite:", err);
      } finally {
        if (!cancelled) setState((prev) => ({ ...prev, loading: false }));
      }
    }
    createInvite();
    return () => {
      cancelled = true;
    };
  }, [open, serverId, channel.id]);

  // Close on Escape
  useEffect(() => {
    const handler = (e: KeyboardEvent) => {
      if (e.key === "Escape") onClose();
    };
    window.addEventListener("keydown", handler);
    return () => window.removeEventListener("keydown", handler);
  }, [onClose]);

  const copyLink = async () => {
    if (!state.inviteCode) return;
    const link = `${getWebOrigin()}/invite/${state.inviteCode}`;
    await navigator.clipboard.writeText(link);
    setState((prev) => ({ ...prev, copied: true }));
    setTimeout(() => setState((prev) => ({ ...prev, copied: false })), 2000);
  };

  const handleInviteUser = (userId: string) => {
    // Mark as invited visually — in a full implementation this would send a DM
    setState((prev) => ({
      ...prev,
      invitedUsers: new Set(prev.invitedUsers).add(userId),
    }));
  };

  const inviteUrl = state.inviteCode
    ? `${getWebOrigin()}/invite/${state.inviteCode}`
    : "";

  return (
    <Dialog open={open} onOpenChange={(nextOpen) => !nextOpen && onClose()}>
      <DialogContent
        showCloseButton={false}
        className="w-full max-w-[480px] overflow-hidden flex flex-col max-h-[80vh]"
      >
        <div>
          {/* Header */}
          <div className="px-6 pt-5 pb-3">
            <DialogClose asChild>
              <IconButton
                icon="close"
                type="button"
                className="absolute right-4 top-4"
                aria-label="Close invite modal"
              />
            </DialogClose>

            <DialogTitle className="text-ui-lg font-semibold text-rm-text">
              Invite friends to{" "}
              <InlineEmojiText
                text={serverName}
                className="text-rm-accent-ink"
              />
            </DialogTitle>
            <DialogDescription className="mt-0.5 flex items-center gap-1 text-sm text-rm-text-muted">
              Recipients will land in <Icon name="textChannel" size="xs" />
              <InlineEmojiText text={channel.name} />
            </DialogDescription>
          </div>

          {/* Search */}
          <div className="px-6 pb-2">
            <div className="relative">
              <label htmlFor={friendSearchInputId} className="sr-only">
                Search friends
              </label>
              <Icon
                name="search"
                size="sm"
                className="absolute left-3 top-1/2 -translate-y-1/2 text-rm-text-muted"
              />
              <Input
                id={friendSearchInputId}
                type="text"
                placeholder="Search for friends"
                value={state.search}
                onChange={(e) =>
                  setState((prev) => ({ ...prev, search: e.target.value }))
                }
                className="pl-9"
              />
            </div>
          </div>

          {/* Friends list */}
          <div className="flex-1 overflow-y-auto px-3 custom-scrollbar min-h-0">
            {friends.length === 0 ? (
              <div className="px-3 py-8 text-center text-sm text-rm-text-muted">
                No friends to invite. Add some friends first!
              </div>
            ) : filteredFriends.length === 0 ? (
              <div className="px-3 py-8 text-center text-sm text-rm-text-muted">
                No friends matching &quot;{state.search}&quot;
              </div>
            ) : (
              filteredFriends.map((rel: Relationship) => {
                const isInvited = state.invitedUsers.has(rel.user.id);
                const displayName =
                  rel.user.display_name?.trim() || rel.user.username;
                return (
                  <div
                    key={rel.user.id}
                    className="flex items-center gap-3 rounded-lg px-3 py-2.5 transition-colors hover:bg-rm-bg-hover"
                  >
                    {/* Avatar */}
                    {rel.user.avatar_url ? (
                      <div className="h-9 w-9 shrink-0 overflow-visible rounded-full">
                        <AvatarImage
                          src={getAuthAssetUrl(rel.user.avatar_url)}
                          alt=""
                          display={rel.user.avatar_display}
                        />
                      </div>
                    ) : (
                      <div className="flex h-9 w-9 shrink-0 items-center justify-center rounded-full bg-primary/10 text-sm font-bold text-primary">
                        {displayName[0].toUpperCase()}
                      </div>
                    )}

                    {/* Name */}
                    <div className="flex-1 min-w-0">
                      <p className="text-sm font-semibold text-rm-text truncate">
                        <InlineEmojiText text={displayName} />
                      </p>
                    </div>

                    {/* Invite button */}
                    <Button
                      type="button"
                      variant={isInvited ? "ghost" : "secondary"}
                      size="sm"
                      onClick={() => handleInviteUser(rel.user.id)}
                      disabled={isInvited}
                      className={cn(isInvited && "text-rm-text-muted")}
                    >
                      {isInvited ? "Invited" : "Invite"}
                    </Button>
                  </div>
                );
              })
            )}
          </div>

          {/* Bottom: invite link */}
          <div className="border-t border-rm-border px-6 py-4">
            <label
              htmlFor={inviteLinkInputId}
              className="mb-2 block text-xs font-medium text-rm-text-muted"
            >
              Or, send a server invite link to a friend
            </label>
            <div className="flex gap-2">
              <Input
                id={inviteLinkInputId}
                value={state.loading ? "Generating..." : inviteUrl}
                readOnly
                onClick={(e) => (e.target as HTMLInputElement).select()}
                className="flex-1 truncate"
              />
              <Button
                type="button"
                variant={state.copied ? "secondary" : "default"}
                onClick={copyLink}
                disabled={state.loading || !state.inviteCode}
                loading={state.loading}
                className={cn("h-9", state.copied && "text-rm-accent-ink")}
              >
                {state.copied ? (
                  <>
                    <Icon name="check" size="sm" /> Copied
                  </>
                ) : (
                  <>
                    <Icon name="copy" size="sm" /> Copy
                  </>
                )}
              </Button>
            </div>
            {state.inviteCode && (
              <p className="mt-2 text-ui-2xs text-rm-text-muted">
                Your invite link expires in 7 days.
              </p>
            )}
          </div>
        </div>
      </DialogContent>
    </Dialog>
  );
}
