#!/usr/bin/env node
/**
 * Builds src/components/ui/icon/glyphs.generated.ts from the raw SVGs in
 * @phosphor-icons/core, shipping only what the app uses: the Bold weight of
 * every mapped glyph, plus the Fill weight of concepts marked `fill: true`.
 * (@phosphor-icons/react bundles all six weights into every icon component.)
 *
 *   pnpm icons:generate          write the file
 *   pnpm icons:generate --check  exit 1 if the file is stale
 *
 * Phosphor is MIT licensed (c) Phosphor Icons.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const iconDir = path.join(root, "src/components/ui/icon");
const outFile = path.join(iconDir, "glyphs.generated.ts");
const check = process.argv.includes("--check");

// mapping.ts is import-free TypeScript; Node strips the types.
const { ICONS } = await import(
  pathToFileURL(path.join(iconDir, "mapping.ts")).href
);

const require = createRequire(path.join(root, "package.json"));
// The package exports its SVGs but not package.json, so resolve an asset.
const coreDir = path.resolve(
  path.dirname(require.resolve("@phosphor-icons/core/assets/bold/x-bold.svg")),
  "../..",
);
const corePkgPath = path.join(coreDir, "package.json");
const coreVersion = JSON.parse(readFileSync(corePkgPath, "utf8")).version;

const SVG_RE =
  /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" viewBox="0 0 256 256" fill="currentColor">((?:<path d="[^"]+"\/>)+)<\/svg>\s*$/;

/** Path data for one glyph weight; fails loudly on anything but plain paths. */
function readPaths(glyph, weight) {
  const file = path.join(coreDir, "assets", weight, `${glyph}-${weight}.svg`);
  let svg;
  try {
    svg = readFileSync(file, "utf8");
  } catch {
    throw new Error(`Phosphor has no "${glyph}" in ${weight} (${file})`);
  }
  const match = SVG_RE.exec(svg);
  if (!match) throw new Error(`Unexpected SVG structure in ${file}`);
  return [...match[1].matchAll(/<path d="([^"]+)"\/>/g)].map((m) =>
    minifyPath(m[1]),
  );
}

/**
 * Round every coordinate to a whole unit of the 256 grid (at most 0.05px off
 * at 24px) and re-serialise compactly. Phosphor relies on implicit
 * separators ("1.4-.05", "22.88.16"), so the path is tokenised, not edited as
 * text. Arc flags are kept verbatim.
 */
const ARGS = { m: 2, l: 2, h: 1, v: 1, c: 6, s: 4, q: 4, t: 2, a: 7, z: 0 };
const TOKEN_RE = /[a-zA-Z]|[-+]?(?:\d+\.?\d*|\.\d+)(?:e[-+]?\d+)?/g;

function minifyPath(d) {
  const tokens = d.match(TOKEN_RE) ?? [];
  let out = "";
  let cmd = "";
  let argIndex = 0;
  let prev = "";
  for (const token of tokens) {
    if (/^[a-zA-Z]$/.test(token)) {
      cmd = token.toLowerCase();
      if (!(cmd in ARGS)) throw new Error(`Unknown path command "${token}"`);
      argIndex = 0;
      out += token;
      prev = token;
      continue;
    }
    const isFlag = cmd === "a" && (argIndex % 7 === 3 || argIndex % 7 === 4);
    let value;
    if (isFlag) {
      if (token !== "0" && token !== "1")
        throw new Error(`Packed arc flag "${token}" in ${d}`);
      value = token;
    } else {
      const n = Math.round(Number(token));
      value = String(Object.is(n, -0) ? 0 : n);
    }
    const needsSeparator = !/^[a-zA-Z]$/.test(prev) && !value.startsWith("-");
    out += (needsSeparator ? "," : "") + value;
    prev = value;
    argIndex++;
  }
  return out;
}

const bold = new Map();
const fill = new Map();
for (const [name, spec] of Object.entries(ICONS)) {
  if (!bold.has(spec.glyph))
    bold.set(spec.glyph, readPaths(spec.glyph, "bold"));
  if (spec.fill && !fill.has(spec.glyph))
    fill.set(spec.glyph, readPaths(spec.glyph, "fill"));
  if (!/^[a-z][a-zA-Z0-9]*$/.test(name))
    throw new Error(`Concept "${name}" must be camelCase`);
}

const sorted = (map) => [...map].sort(([a], [b]) => a.localeCompare(b));
const emit = (map) =>
  sorted(map)
    .map(
      ([glyph, paths]) =>
        `  "${glyph}": [${paths.map((d) => JSON.stringify(d)).join(", ")}],`,
    )
    .join("\n");

const output = `// Generated by scripts/generate-phosphor-icons.mjs from @phosphor-icons/core
// ${coreVersion} (MIT, (c) Phosphor Icons). Do not edit; edit mapping.ts and
// run \`pnpm icons:generate\`. ${bold.size} Bold glyphs, ${fill.size} Fill glyphs, 256 x 256.

export type GlyphPaths = readonly string[];

export const BOLD: Readonly<Record<string, GlyphPaths>> = {
${emit(bold)}
};

export const FILL: Readonly<Record<string, GlyphPaths>> = {
${emit(fill)}
};
`;

if (check) {
  let current = "";
  try {
    current = readFileSync(outFile, "utf8");
  } catch {}
  if (current.replace(/\r\n/g, "\n") !== output) {
    console.error("glyphs.generated.ts is stale. Run `pnpm icons:generate`.");
    process.exit(1);
  }
  console.log("glyphs.generated.ts is up to date.");
} else {
  writeFileSync(outFile, output);
  console.log(
    `Wrote ${path.relative(root, outFile)}: ${bold.size} Bold, ${fill.size} Fill.`,
  );
}
